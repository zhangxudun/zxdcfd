# -*- coding: utf-8 -*-
'''按 docs/08-判定与回退.md 给出结论: 第 7 步的结果，或第 2–7 步的报错 -> 通过，或返工并指出回到哪一步。

用法:
    from judge_result import judge_result
    结论 = judge_result(输入)
    结论['结论']        # '通过' 或 '返工'；另有 回到步骤、对照一维、原因

    输入: 第 7 步 check_result 的返回值，或算例目录的路径（读里面的 结果.json），
          或第 2–7 步抛出的异常对象（校验错误、标注错误、工况错误、网格错误、算例错误、求解错误、结果错误）。

命令行:
    python judge_result.py 算例目录
    通过返回 0，返工或不能判定返回 1，用法不对返回 2。

结局分三种:
    通过: 结果里最外层的 通过 和每一项检查都为 True。回到步骤、原因 都为空。
    返工: 有检查项不通过，或者输入是前面步骤的报错。每条原因写明 现象、回到步骤、处理、说明。
          原因里的 回到步骤 按先试哪一步排；最外层的 回到步骤 是各原因的并集，从小到大。
          说明 照抄 结果.json 里该项的说明或异常信息，不重新算数。
    不能判定: 结果.json 缺失、不完整或自相矛盾，或者输入不是上面三种。抛 判定错误，不给结论。

这一步只判定，不返工: 不写文件，不改传入的字典和异常，不调用第 1–7 步，不运行 OpenFOAM。
不导入前面步骤的模块，异常按类名识别，所以不依赖 gmsh。

回退规则见下面的 检查规则 和 异常规则。同一类异常按表中先后看信息里的关键字，None 表示其余情况。
与 docs/08 第 2.4 节有一处不同: 结果错误 先看“第 5 步”再看“监测量”，
因为 check_result 在 算例信息.json 缺 监测量 时的报错也带“监测量”三个字，那种情况要回第 5 步。
'''
import json
import os


class 判定错误(ValueError):
    '''结果.json 缺失、不完整或自相矛盾，或者输入既不是第 7 步的结果也不是第 2–7 步的异常。'''


结果文件名 = '结果.json'
基本检查 = ('流量守恒', '入口流量', '监测值稳定', '残差收敛')
一维检查 = ('压差与一维解一致', '出口温度与一维解一致')
水侧检查 = ('水侧稳定', '热平衡', '水未沸腾')          # 多孔区是水侧耦合时紧跟在基本检查后面
水侧一维检查 = ('水出口温度与一维解一致',)               # 水侧耦合并且对照一维时排在最后
规定组合 = (基本检查, 基本检查 + 一维检查, 基本检查 + 水侧检查, 基本检查 + 水侧检查 + 一维检查 + 水侧一维检查)
旧项目名 = {'出口烟温与一维解一致': '出口温度与一维解一致'}    # 旧版第 7 步写的 结果.json 仍然能判定

_步数或网格 = ((5, 4), '按原因增加求解步数，或加密网格后重跑')
_标注或网格 = ((2, 4), '先核对多孔体、流向和一维估算是否适用，再检查网格')
_改网格 = ((4,), '减小网格尺寸，或修几何')

检查规则 = {
    '流量守恒': _步数或网格,
    '监测值稳定': _步数或网格,
    '残差收敛': _步数或网格,
    '入口流量': ((2, 4), '先核对入口面的标注和入口速度，再加密网格'),
    '压差与一维解一致': _标注或网格,
    '出口温度与一维解一致': _标注或网格,
    '水侧稳定': _步数或网格,
    '热平衡': _步数或网格,
    '水未沸腾': ((2,), '水侧到了饱和温度（省煤器沸腾）: 加大水流量或降低水入口温度；两相超出本流程'),
    '水出口温度与一维解一致': _标注或网格,
}

异常规则 = {
    '校验错误': ((None, (2,), '在标注里指定面编号'),),
    '标注错误': ((None, (2,), '改标注后重跑'),),
    '工况错误': ((None, (2,), '改工况后重跑'),),
    '网格错误': ((None,) + _改网格,),
    '算例错误': ((None, (5,), '按异常信息改输入后重写算例'),),
    '求解错误': (
        (('checkMesh 不通过',),) + _改网格,
        (('找不到 docker', '环境里找不到 OpenFOAM', '超时', '启动不了'), (6,),
         '修好环境或加大时限后重跑第 6 步，算例不用改'),
        (('第 5 步',), (5,), '重新写算例'),
        (None, (5, 4), '先查算例设置和步数，再检查网格'),
    ),
    '结果错误': (
        (('一维估算',), (7,), '不做一维对照，仅执行四项基本检查'),
        (('第 5 步',), (5,), '重新写算例'),
        (('残差',), (6,), '重新求解'),
        (('监测量',), (6,), '重新求解'),
        (None, (5,), '重新写算例'),
    ),
}


def _汇总(原因, 对照一维):
    步骤 = sorted({n for 项 in 原因 for n in 项['回到步骤']})
    return {'结论': '返工' if 原因 else '通过', '回到步骤': 步骤, '对照一维': 对照一维, '原因': 原因}


def _判异常(异常):
    for 类 in type(异常).__mro__:
        if 类.__name__ in 异常规则:
            break
    else:
        raise 判定错误('不是第 2–7 步的异常，不能判定: %s: %s' % (type(异常).__name__, 异常))
    说明 = str(异常)
    for 关键字, 步骤, 处理 in 异常规则[类.__name__]:
        if 关键字 is None or any(字 in 说明 for 字 in 关键字):
            return _汇总([{'现象': '报错（%s）' % 类.__name__, '回到步骤': list(步骤),
                           '处理': 处理, '说明': 说明}], False)


def _读结果(输入):
    目录 = os.path.abspath(os.fspath(输入))
    if not os.path.isdir(目录):
        raise 判定错误('找不到算例目录: %s' % 目录)
    路径 = os.path.join(目录, 结果文件名)
    if not os.path.isfile(路径):
        raise 判定错误('算例目录里没有 %s: %s，请先运行第 7 步' % (结果文件名, 目录))
    try:
        with open(路径, encoding='utf-8') as f:
            结果 = json.load(f)
    except (OSError, ValueError) as e:
        raise 判定错误('%s 读不了: %s (%s)，请重新运行第 7 步' % (结果文件名, 路径, e)) from e
    if not isinstance(结果, dict):
        raise 判定错误('%s 读不了: 内容不是字典，请重新运行第 7 步' % 结果文件名)
    return 结果


def _判结果(结果):
    for 键 in ('通过', '检查'):
        if 键 not in 结果:
            raise 判定错误('结果里没有 %s，请重新运行第 7 步' % 键)
    if not isinstance(结果['通过'], bool):
        raise 判定错误('结果里的 通过 不是布尔值（%r），请重新运行第 7 步' % (结果['通过'],))
    检查 = 结果['检查']
    if not isinstance(检查, list):
        raise 判定错误('结果里的 检查 不是列表，请重新运行第 7 步')
    for i, 项 in enumerate(检查, 1):
        if not isinstance(项, dict):
            raise 判定错误('检查 的第 %d 项不是字典，请重新运行第 7 步' % i)
        for 键 in ('项目', '通过'):
            if 键 not in 项:
                raise 判定错误('检查 的第 %d 项没有 %s，请重新运行第 7 步' % (i, 键))
        if not isinstance(项['项目'], str):
            raise 判定错误('检查 的第 %d 项的 项目 不是文字（%r），请重新运行第 7 步' % (i, 项['项目']))
        if not isinstance(项['通过'], bool):
            raise 判定错误('检查 的第 %d 项（%s）的 通过 不是布尔值（%r），请重新运行第 7 步'
                           % (i, 项['项目'], 项['通过']))
        if not isinstance(项.get('说明', ''), str):
            raise 判定错误('检查 的第 %d 项（%s）的 说明 不是文字，请重新运行第 7 步' % (i, 项['项目']))
    检查 = [dict(项, 项目=旧项目名.get(项['项目'], 项['项目'])) for 项 in 检查]
    项目 = tuple(项['项目'] for 项 in 检查)
    if 项目 not in 规定组合:
        不认识 = [名 for 名 in 项目 if 名 not in 检查规则]
        重复 = sorted({名 for 名 in 项目 if 项目.count(名) > 1})
        if 不认识:
            问题 = '有不认识的项目 %s' % '、'.join(不认识)
        elif 重复:
            问题 = '项目 %s 重复' % '、'.join(重复)
        else:
            问题 = '实际是 %d 项: %s' % (len(项目), '、'.join(项目) or '空')
        raise 判定错误('检查 不是规定的四项或六项（顺序: %s；水侧耦合时在基本检查后加 %s，对照一维时最后再加 %s）: '
                       '%s，请重新运行第 7 步'
                       % ('、'.join(基本检查 + 一维检查), '、'.join(水侧检查), '、'.join(水侧一维检查), 问题))
    不通过 = [项 for 项 in 检查 if not 项['通过']]
    if 结果['通过'] != (not 不通过):
        raise 判定错误('最外层的 通过 与各项不一致: 最外层为 %s，不通过的检查项是 %s，请重新运行第 7 步'
                       % (结果['通过'], '、'.join(项['项目'] for 项 in 不通过) or '无'))
    原因 = [{'现象': '%s不通过' % 项['项目'], '回到步骤': list(检查规则[项['项目']][0]),
             '处理': 检查规则[项['项目']][1], '说明': 项.get('说明', '')} for 项 in 不通过]
    return _汇总(原因, 一维检查[0] in 项目)


def judge_result(输入):
    '''判定通过还是返工，返回:

        {'结论': '通过' 或 '返工', '回到步骤': [步骤编号，从小到大], '对照一维': 布尔,
         '原因': [{'现象': 文字, '回到步骤': [先试的在前], '处理': 文字, '说明': 文字}, ...]}

    不能判定时抛 判定错误。不写文件，不改动输入。
    '''
    if isinstance(输入, BaseException):
        return _判异常(输入)
    if isinstance(输入, dict):
        return _判结果(输入)
    if isinstance(输入, (str, os.PathLike)):
        return _判结果(_读结果(输入))
    raise 判定错误('输入必须是第 7 步的返回值、算例目录的路径，或第 2–7 步抛出的异常，实际为 %r' % (输入,))


def _步骤文字(步骤):
    return '第 %s 步' % '、'.join(str(n) for n in 步骤)


def _命令行(参数):
    '''返回退出码: 通过 0，返工或不能判定 1，用法不对 2。'''
    import sys
    if len(参数) != 1 or 参数[0].startswith('--'):
        print(__doc__)
        return 2
    try:
        结论 = judge_result(参数[0])
    except 判定错误 as e:
        print('不能判定: %s' % e, file=sys.stderr)
        return 1
    for 项 in 结论['原因']:
        print('%s，回到%s: %s。%s' % (项['现象'], _步骤文字(项['回到步骤']), 项['处理'], 项['说明']))
    if 结论['结论'] == '通过':
        print('结论: 通过（%s）' % ('含一维对照' if 结论['对照一维'] else '未对照一维'))
        return 0
    print('结论: 返工，回到%s' % _步骤文字(结论['回到步骤']))
    return 1


if __name__ == '__main__':
    import sys
    sys.exit(_命令行(sys.argv[1:]))
